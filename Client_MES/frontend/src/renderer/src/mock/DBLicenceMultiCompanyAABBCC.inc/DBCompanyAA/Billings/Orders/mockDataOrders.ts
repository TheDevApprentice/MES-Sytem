function calculateOrderLineTotal(orderLine: OrderLine) {
  // pour l'order line on va chercher le produit correspondant
  const product = products.find((product: Product) => product.id === orderLine.productId)
  // et on retourne le calcul du total basé sur le prix du produit, la quantité et le discount
  return orderLine.quantity * product.price * (1 - (product.discount || 0) / 100)
}

